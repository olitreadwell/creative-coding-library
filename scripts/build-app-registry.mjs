#!/usr/bin/env node
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function toImportIdentifier(slug) {
  return "meta_" + slug.replace(/[^a-zA-Z0-9]/g, "_").replace(/^([0-9])/, "_$1");
}

export function toImportPath(file, outFile) {
  const rel = path.relative(path.dirname(outFile), file).replace(/\\/g, "/");
  return rel.replace(/\.ts$/, "");
}

export async function findMetaFiles(appsDir) {
  let entries;
  try {
    entries = await fs.readdir(appsDir, { withFileTypes: true });
  } catch (err) {
    if (err.code === "ENOENT") return [];
    throw err;
  }
  const results = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name.startsWith("_") || entry.name.startsWith(".")) continue;
    const candidate = path.join(appsDir, entry.name, "app.meta.ts");
    try {
      await fs.access(candidate);
      results.push({ slug: entry.name, file: candidate });
    } catch {}
  }
  results.sort((a, b) => a.slug.localeCompare(b.slug));
  return results;
}

export function renderRegistry(found, outFile) {
  const imports = found
    .map(
      ({ slug, file }) =>
        `import { meta as ${toImportIdentifier(slug)} } from "${toImportPath(file, outFile)}";`,
    )
    .join("\n");
  const items = found.map(({ slug }) => `  ${toImportIdentifier(slug)},`).join("\n");
  const banner = `// AUTO-GENERATED by scripts/build-app-registry.mjs — do not edit by hand.\n// Run \`pnpm registry\` to regenerate.\n`;
  return `${banner}\nimport type { AppMeta } from "./registry";\n${imports ? imports + "\n" : ""}\nexport const apps: readonly AppMeta[] = ${
    found.length === 0 ? "[]" : `[\n${items}\n]`
  } as const;\n`;
}

export async function buildRegistry({ appsDir, outFile }) {
  const found = await findMetaFiles(appsDir);
  const body = renderRegistry(found, outFile);
  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, body, "utf8");
  return { count: found.length, outFile };
}

