if (isMain) {
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = path.dirname(__filename);
  const repoRoot = path.resolve(__dirname, "..");
  const appsDir = path.join(repoRoot, "src", "app");
  const outFile = path.join(repoRoot, "src", "lib", "creative", "registry.generated.ts");
  buildRegistry({ appsDir, outFile })
    .then(({ count, outFile: out }) =>
      process.stdout.write(`registry: ${count} app(s) -> ${path.relative(repoRoot, out)}\n`),
    )
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
